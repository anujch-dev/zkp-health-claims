const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("=== Deploying ZK-HealthClaims Smart Contracts ===");

  const [deployer] = await hre.ethers.getSigners();
  console.log("Deployer Address:", deployer.address);
  console.log("Deployer Balance:", hre.ethers.formatEther(await hre.ethers.provider.getBalance(deployer.address)), "ETH");

  // 1. Deploy HealthAccessRegistry
  console.log("\n1. Deploying HealthAccessRegistry...");
  const HealthAccessRegistry = await hre.ethers.getContractFactory("HealthAccessRegistry");
  const registry = await HealthAccessRegistry.deploy();
  await registry.waitForDeployment();
  const registryAddress = await registry.getAddress();
  console.log("✓ HealthAccessRegistry deployed at:", registryAddress);

  // 2. Deploy Real Groth16Verifier (BN254 Pairing Verifier)
  console.log("\n2. Deploying Real Groth16Verifier (BN254 Pairing Verifier)...");
  const Groth16Verifier = await hre.ethers.getContractFactory("Groth16Verifier");
  const verifier = await Groth16Verifier.deploy();
  await verifier.waitForDeployment();
  const verifierAddress = await verifier.getAddress();
  console.log("✓ Groth16Verifier deployed at:", verifierAddress);

  // 3. Deploy ZKPInsuranceSettlement
  // Approved Hospital Merkle Root (Poseidon 4-leaf tree root matching circuit)
  const rootBigInt = BigInt("8464722192574004154307101905833932193053562928359214660920880496777686120894");
  const HOSPITAL_MERKLE_ROOT_BYTES32 = hre.ethers.toBeHex(rootBigInt, 32);
  const initialLiquidity = hre.ethers.parseEther("25.0"); // 25 ETH liquidity escrow

  console.log("\n3. Deploying ZKPInsuranceSettlement with initial 25 ETH escrow...");
  const ZKPInsuranceSettlement = await hre.ethers.getContractFactory("ZKPInsuranceSettlement");
  const settlement = await ZKPInsuranceSettlement.deploy(
    verifierAddress,
    HOSPITAL_MERKLE_ROOT_BYTES32,
    { value: initialLiquidity }
  );
  await settlement.waitForDeployment();
  const settlementAddress = await settlement.getAddress();
  console.log("✓ ZKPInsuranceSettlement deployed at:", settlementAddress);
  console.log("  Approved Merkle Root (Bytes32):", HOSPITAL_MERKLE_ROOT_BYTES32);
  console.log("  Approved Merkle Root (Decimal):", rootBigInt.toString());
  console.log("  Escrow Balance:", hre.ethers.formatEther(await hre.ethers.provider.getBalance(settlementAddress)), "ETH");

  // 4. Export deployment addresses to JSON file
  const deploymentData = {
    network: hre.network.name,
    chainId: (await hre.ethers.provider.getNetwork()).chainId.toString(),
    deployedAt: new Date().toISOString(),
    contracts: {
      HealthAccessRegistry: registryAddress,
      Groth16Verifier: verifierAddress,
      ZKPInsuranceSettlement: settlementAddress
    },
    approvedHospitalMerkleRoot: HOSPITAL_MERKLE_ROOT_BYTES32,
    approvedHospitalMerkleRootDecimal: rootBigInt.toString()
  };

  const outputPath = path.join(__dirname, "..", "deployed-addresses.json");
  fs.writeFileSync(outputPath, JSON.stringify(deploymentData, null, 2));
  console.log("\n✓ Deployment details exported to:", outputPath);

  // 5. Also export TypeScript config to frontend
  const frontendContractsDir = path.join(__dirname, "..", "..", "frontend", "src", "contracts");
  if (!fs.existsSync(frontendContractsDir)) {
    fs.mkdirSync(frontendContractsDir, { recursive: true });
  }

  const tsContent = `// Auto-generated by Hardhat deployment script (${new Date().toISOString()})
export const DEPLOYED_ADDRESSES = {
  network: "${hre.network.name}",
  chainId: "${(await hre.ethers.provider.getNetwork()).chainId.toString()}",
  HealthAccessRegistry: "${registryAddress}",
  Groth16Verifier: "${verifierAddress}",
  ZKPInsuranceSettlement: "${settlementAddress}",
  approvedHospitalMerkleRoot: "${HOSPITAL_MERKLE_ROOT_BYTES32}",
  approvedHospitalMerkleRootDecimal: "${rootBigInt.toString()}"
} as const;
`;

  fs.writeFileSync(path.join(frontendContractsDir, "deployedAddresses.ts"), tsContent);
  console.log("✓ Frontend contracts config exported to:", path.join(frontendContractsDir, "deployedAddresses.ts"));
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
